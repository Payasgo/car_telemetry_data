-- Run once in Supabase SQL Editor for the KM Autos private cloud dashboard.
-- Replace no values here: owner_id is assigned by the trusted local sync worker.

create table if not exists public.telemetry_events (
    id bigint generated by default as identity primary key,
    origin_id text not null unique,
    owner_id uuid not null references auth.users(id) on delete cascade,
    created_at timestamptz not null,
    source text not null check (source in ('obd', 'esp32')),
    payload jsonb not null
);

-- Upgrade an earlier prototype table if it already exists.
alter table public.telemetry_events
    add column if not exists origin_id text,
    add column if not exists owner_id uuid references auth.users(id) on delete cascade;

create unique index if not exists telemetry_events_origin_id_uidx
    on public.telemetry_events(origin_id)
    ;

create index if not exists telemetry_events_owner_created_idx
    on public.telemetry_events(owner_id, created_at desc);

alter table public.telemetry_events enable row level security;

-- Remove permissive prototype policies if previously created.
drop policy if exists "Allow authenticated inserts" on public.telemetry_events;
drop policy if exists "Allow public inserts" on public.telemetry_events;
drop policy if exists "Users can read own telemetry" on public.telemetry_events;

create policy "Users can read own telemetry"
    on public.telemetry_events
    for select
    to authenticated
    using (owner_id = auth.uid());

-- No anon/authenticated INSERT, UPDATE or DELETE policy is created.
-- Local sync uses the service_role key from the laptop's private .env file.
-- service_role bypasses RLS; NEVER expose that key in Streamlit Cloud or GitHub.

grant select on public.telemetry_events to authenticated;
